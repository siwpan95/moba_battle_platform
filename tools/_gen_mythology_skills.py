# ── helpers ──
def _eff(typ, target, duration=1, desc="", value=None):
    e = {"type": typ, "target": target, "duration": duration, "desc": desc}
    if value is not None:
        e["value"] = value
    return e

def _st(attr, on_save="半伤"):
    return {"attr": attr, "dc_formula": f"8+PROF+{attr}", "on_save": on_save}

def _dmg(count, size, attr, dmg_type):
    return {"dice_count": count, "dice_size": size, "bonus_attr": attr, "type": dmg_type}

def _make_skill(name, key, cd, stype, action, rng, target, dmg, effects, desc, save=None, aoe=None):
    s = {
        "name": name, "key": key, "type": stype, "action": action,
        "range": rng, "target": target, "damage": dmg,
        "effects": effects, "cooldown": cd, "description": desc, "approx": True
    }
    if save:
        s["saving_throw"] = save
    if aoe:
        s["aoe_radius"] = aoe
    return s

