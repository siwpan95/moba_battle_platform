# Skill helper
def skill(name, key, type_, action, range_, target, dcount, dsize, dattr, dtype,
          effects, cooldown, desc, saving_throw=None, aoe_radius=None):
    s = {
        'name': name, 'key': key, 'type': type_, 'action': action,
        'range': range_, 'target': target,
        'damage': {'dice_count': dcount, 'dice_size': dsize,
                    'bonus_attr': dattr, 'type': dtype},
        'effects': effects, 'cooldown': cooldown, 'description': desc
    }
    if saving_throw: s['saving_throw'] = saving_throw
    if aoe_radius: s['aoe_radius'] = aoe_radius
    return s

def eff(type_, target, duration, desc):
    return {'type': type_, 'target': target, 'duration': duration, 'desc': desc}

def st(attr, on_save):
    return {'attr': attr, 'dc_formula': f'8+PROF+{attr}', 'on_save': on_save}

