def _load_smite_pool() -> dict:
    """从技能池目录 data/skills/smite/ 加载合并为 {英雄: 技能}，回退旧大文件。"""
    pool = os.path.join(PROJECT, "data", "skills", "smite")
    if os.path.isdir(pool):
        data = {}
        for fn in os.listdir(pool):
            if fn.endswith(".json"):
                try:
                    with open(os.path.join(pool, fn), "r", encoding="utf-8") as f:
                        data[fn[:-5]] = json.load(f)
                except (json.JSONDecodeError, OSError):
                    continue
        return data
    if os.path.exists(SMITE_PATH):
        with open(SMITE_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    return {}


