# ── 技能工厂 ──
def sk(name, key, typ, rng, tgt, dmg, effs, cd, desc, aoe=None, st=None):
    s = {
        "name": name, "key": key, "type": typ, "action": "动作",
        "range": rng, "target": tgt,
        "damage": dmg,
        "effects": effs,
        "cooldown": cd,
        "description": desc
    }
    if aoe: s["aoe_radius"] = aoe
    if st: s["saving_throw"] = st
    return s

def eff(typ, desc, dur=None, tgt="敌方", vf=None, val=None):
    e = {"type": typ, "desc": desc, "target": tgt}
    if dur is not None: e["duration"] = dur
    if vf: e["value_formula"] = vf
    if val is not None: e["value"] = val
    return e

def dmg(dc, ds, ba, dt):
    return {"dice_count": dc, "dice_size": ds, "bonus_attr": ba, "type": dt}

def ssave(attr, dc_f, on_save):
    return {"attr": attr, "dc_formula": dc_f, "on_save": on_save}

