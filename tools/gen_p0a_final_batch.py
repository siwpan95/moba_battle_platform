BATCH_SIZE = 20


def process_ip(ip_name, dry_run=False, batch_id=None):
    """处理单个 IP，可选分批"""
    cfg = IP_CONFIGS[ip_name]
    skills_path = os.path.join(PROJECT_ROOT, cfg["path"])
    existing = load_existing(skills_path)

    # 找出缺失英雄
    all_new = []
    for name, role, skill_defs, effect_defs in cfg["heroes"]:
        if name not in existing:
            # merge skill_defs and effect_defs
            merged = {}
            for key in cfg["keys"]:
                sname = skill_defs.get(key, f"{name}技{key}")
                merged[key] = {
                    "name": sname,
                    "effect": effect_defs.get(key),
                }
            all_new.append((name, role, merged))

    if batch_id is not None:
        start = batch_id * BATCH_SIZE
        end = min(start + BATCH_SIZE, len(all_new))
        batch = all_new[start:end]
        print(f"[{ip_name}] Batch {batch_id}: {len(batch)} heroes ({start+1}-{end} of {len(all_new)} new)")
    else:
        batch = all_new
        print(f"[{ip_name}] Processing all {len(batch)} new heroes")

    if not batch:
        print(f"[{ip_name}] All heroes already exist! Total: {len(existing)}")
        return existing

    new_skills = {}
    for name, role, skill_defs in batch:
        if cfg["build_fn"] == "build_4":
            skills = build_hero_skills_4(name, role, skill_defs, cfg["keys"])
        else:
            skills = build_hero_skills_3(name, role, skill_defs, cfg["keys"])
        new_skills[name] = skills

    if dry_run:
        print(f"  [DRY RUN] Would write {len(new_skills)} heroes to {cfg['path']}")
        for h in list(new_skills.keys())[:3]:
            print(f"  Sample {h}:")
            for s in new_skills[h]:
                print(f"    [{s['key']}] {s['name']} CD={s['cooldown']} {s['description'][:60]}...")
        return new_skills

    # Merge and save
    existing.update(new_skills)
    save_skills(existing, skills_path)

    total_heroes = len(existing)
    total_skills = sum(len(v) for v in existing.values())
    print(f"  Saved! Total: {total_heroes} heroes, {total_skills} skills in {cfg['path']}")

    # Quick validation
    issues = []
    expected_keys = set(cfg["keys"])
    for hname, hskills in existing.items():
        actual_keys = [s["key"] for s in hskills]
        if set(actual_keys) != expected_keys:
            issues.append(f"  BAD KEYS: {hname} has keys {actual_keys}")
        for s in hskills:
            if s["cooldown"] not in [0, 1, 2, 4]:
                issues.append(f"  BAD CD: {hname}/{s['key']} CD={s['cooldown']}")
            if s.get("damage", {}).get("dice_count", 1) < 0:
                issues.append(f"  BAD DICE: {hname}/{s['key']}")

    if issues:
        print(f"  WARNINGS ({len(issues)}):")
        for i in issues[:10]:
            print(f"    {i}")

    return existing


def main():
    parser = argparse.ArgumentParser(description="P0-A Final Batch: 5 IP skill generator")
    parser.add_argument("ip", choices=["all", "heroes_of_the_storm", "onmyoji_arena",
                                        "pokemon_unite", "marvel_super_war", "vainglory"])
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--batch", type=int, default=None)
    args = parser.parse_args()

    ips = list(IP_CONFIGS.keys()) if args.ip == "all" else [args.ip]

    totals = {}
    for ip_name in ips:
        print(f"\n{'='*60}")
        print(f"Processing: {ip_name}")
        print(f"{'='*60}")
        result = process_ip(ip_name, args.dry_run, args.batch)
        totals[ip_name] = {"heroes": len(result), "skills": sum(len(v) for v in result.values())}

    print(f"\n{'='*60}")
    print("SUMMARY")
    print(f"{'='*60}")
    grand_heroes = sum(t["heroes"] for t in totals.values())
    grand_skills = sum(t["skills"] for t in totals.values())
    for ip, t in totals.items():
        print(f"  {ip}: {t['heroes']} heroes, {t['skills']} skills")
    print(f"  TOTAL: {grand_heroes} heroes, {grand_skills} skills")


if __name__ == "__main__":
    main()
