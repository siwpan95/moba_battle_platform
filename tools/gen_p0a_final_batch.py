def build_skill(hero_name, role, key, skill_name, effect_alias=None):
    """基于角色模板生成单个 D&D 技能"""
    tmpl = SKILL_TEMPLATES.get(role, SKILL_TEMPLATES["fighter"])
    # map key to template slot
    slot_map = {"Q": "Q", "1": "Q", "A": "Q",
                "W": "W", "2": "W", "B": "W",
                "E": "E", "3": "E",
                "R": "R", "4": "R", "U": "R"}
    slot = slot_map.get(key, "Q")
    t = tmpl.get(slot, tmpl["Q"])
    attr = ROLE_ATTR_MAP.get(role, ROLE_ATTR_MAP["fighter"])
    cd = KEY_CD_MAP.get(key, 0)

    dc, ds = t["dice"]
    damage = {
        "dice_count": dc,
        "dice_size": ds,
        "bonus_attr": attr["bonus"],
        "type": t["dmg"],
    }

    # Build effects from alias
    effects = []
    desc_parts = [f"{dc}d{ds}+{attr['bonus']} {t['dmg']}伤害"]

    if effect_alias and effect_alias in EFFECT_ALIASES:
        eff = dict(EFFECT_ALIASES[effect_alias])
        is_self = eff.get("target") in ("自身", "友方")
        if "duration" not in eff or eff["duration"] is None:
            eff["duration"] = 1
        effects.append(eff)
        dur = eff.get("duration", "")
        dur_str = f"{dur}回合" if dur else ""
        desc_parts.append(f"{eff.get('desc','')}{dur_str}")

    # Use default role-slot effect if none provided
    elif effect_alias is None:
        default_eff = ROLE_SLOT_EFFECTS.get(role, {}).get(slot)
        if default_eff and default_eff in EFFECT_ALIASES:
            eff = dict(EFFECT_ALIASES[default_eff])
            if "duration" not in eff or eff["duration"] is None:
                eff["duration"] = 1
            effects.append(eff)
            dur = eff.get("duration", "")
            dur_str = f"{dur}回合" if dur else ""
            desc_parts.append(f"{eff.get('desc','')}{dur_str}")

    description = "。".join(desc_parts) + "。"

    # Build saving_throw for control effects
    saving_throw = None
    for e in effects:
        if e.get("dc_attr"):
            saving_throw = {
                "attr": e["dc_attr"],
                "dc_formula": f"8+PROF+{attr['dc']}",
                "on_save": "无效",
            }
            break

    skill = {
        "name": skill_name,
        "key": key,
        "type": t["type"],
        "action": "动作",
        "range": t["range"],
        "target": t["target"],
        "damage": damage,
        "cooldown": cd,
        "description": description,
    }
    if effects:
        skill["effects"] = effects
    if saving_throw:
        skill["saving_throw"] = saving_throw
    if "aoe" in t and t["aoe"]:
        skill["aoe_radius"] = t["aoe"]

    return skill


def build_hero_skills_4(hero_name, role, skill_defs, key_order):
    """为一个英雄生成技能列表（4技能）"""
    skills = []
    for key in key_order:
        sd = skill_defs.get(key, {})
        name = sd.get("name", f"{hero_name}技{key}")
        effect = sd.get("effect")
        skill = build_skill(hero_name, role, key, name, effect)
        skills.append(skill)
    return skills


def build_hero_skills_3(hero_name, role, skill_defs, key_order):
    """为一个英雄生成技能列表（3技能, Vainglory）"""
    # 3-skill: use Q/W/R template slots for A/B/U
    skills = []
    for key in key_order:
        sd = skill_defs.get(key, {})
        name = sd.get("name", f"{hero_name}技{key}")
        effect = sd.get("effect")
        skill = build_skill(hero_name, role, key, name, effect)
        skills.append(skill)
    return skills


def load_existing(skills_path):
    if os.path.exists(skills_path):
        with open(skills_path, "r", encoding="utf-8") as f:
            return json.load(f)
    return {}


def save_skills(data, skills_path):
    """将技能数据写入技能池：data/skills/<ip>/<英雄>.json（每英雄独立文件）。

    skills_path 形如 data/skills/<ip>.json，从中提取 ip 作为池目录名。
    """
    ip = os.path.splitext(os.path.basename(skills_path))[0]
    for name, skills in data.items():
        write_hero_skill(ip, name, skills)


