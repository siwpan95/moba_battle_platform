def skill_needs_effects(skill):
    """只有 effects 为空列表时才补"""
    return isinstance(skill.get("effects"), list) and len(skill["effects"]) == 0


def infer_effects(skill_name):
    """基于技能名推断 1-2 个合理 effects"""
    results = []
    for keywords, etype, target, duration, desc in RULES:
        for kw in keywords:
            if kw in skill_name:
                results.append({
                    "type": etype,
                    "target": target,
                    "duration": duration,
                    "desc": desc
                })
                break
        if len(results) >= 2:
            break
    # 如果没有匹配到任何规则，根据 damage type 给一个最基础的效果
    if not results:
        return []
    return results[:2]


def main():
    total_filled = 0
    total_skills = 0

    for relpath in FILES:
        ip = os.path.splitext(os.path.basename(relpath))[0]
        pool = os.path.join(PROJECT_ROOT, "data", "skills", ip)

        # ── 技能池模式：逐英雄文件补 effects ──
        if os.path.isdir(pool):
            hero_files = [fn for fn in os.listdir(pool) if fn.endswith(".json")]
            file_filled = 0
            file_total = 0
            for fn in hero_files:
                fp = os.path.join(pool, fn)
                try:
                    with open(fp, "r", encoding="utf-8") as f:
                        skills = json.load(f)
                except (json.JSONDecodeError, OSError):
                    continue
                for skill in skills:
                    file_total += 1
                    if skill_needs_effects(skill):
                        effects = infer_effects(skill["name"])
                        if effects:
                            skill["effects"] = effects
                            file_filled += 1
                            total_filled += 1
                    total_skills += 1
                with open(fp, "w", encoding="utf-8") as f:
                    json.dump(skills, f, ensure_ascii=False, indent=2)
                    f.write("\n")
            print(f"[{ip}] {file_filled}/{file_total} skills filled with effects (pool)")
            continue

        # ── 回退旧大文件模式 ──
        filepath = os.path.join(PROJECT_ROOT, relpath)
        if not os.path.exists(filepath):
            print(f"[{ip}] 跳过：无技能数据（池与大文件均不存在）")
            continue
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)

        file_filled = 0
        file_total = 0

        for hero_name, skills in data.items():
            for skill in skills:
                file_total += 1
                if skill_needs_effects(skill):
                    effects = infer_effects(skill["name"])
                    if effects:
                        skill["effects"] = effects
                        file_filled += 1
                        total_filled += 1
                total_skills += 1

        # 写回
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")

        ip_name = os.path.splitext(os.path.basename(filepath))[0]
        print(f"[{ip_name}] {file_filled}/{file_total} skills filled with effects")

    print(f"\n总计: {total_filled} effects filled across {total_skills} skills in {len(FILES)} files")
    return 0


